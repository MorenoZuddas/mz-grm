function resolveEquipmentItem(item: EquipmentCatalogItem, section: EquipmentSection): EquipmentItem {
  const { sections: _sections, categoryOverrides, sortOrder: _sortOrder, ...baseItem } = item;

  return {
    ...baseItem,
    category: categoryOverrides?.[section] ?? baseItem.category,
  };
}

export function getEquipmentBySection(section: EquipmentSection): EquipmentItem[] {
  return equipmentCatalog
    .filter((item) => item.sections.includes(section))
    .sort((a, b) => {
      const aOrder = a.sortOrder?.[section] ?? Number.MAX_SAFE_INTEGER;
      const bOrder = b.sortOrder?.[section] ?? Number.MAX_SAFE_INTEGER;
      return aOrder - bOrder;
    })
    .map((item) => resolveEquipmentItem(item, section));
}


